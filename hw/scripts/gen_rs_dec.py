#!/usr/bin/env python3
"""Generates hw/rtl/rs_dec.v (GF tables are inlined as case statements).
Re-run after changing RS_NSYM / RS_FCR / GF_PRIM in model/ldacs_ref.py."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "model"))
import ldacs_ref as L

exp_cases = "\n".join(f"            8'd{i}: gf_exp = 8'h{L.GF_EXP[i]:02x};" for i in range(255))
inv_cases = "\n".join(f"            8'h{a:02x}: gf_inv = 8'h{L.gf_inv(a):02x};" for a in range(1, 256))
prim_low = L.GF_PRIM & 0xFF

v = f"""// ============================================================================
// rs_dec.v - Reed-Solomon decoder over GF(2^8)   (GENERATED by hw/scripts/gen_rs_dec.py)
//   field polynomial 0x{L.GF_PRIM:03X}, NSYM = {L.RS_NSYM} parity bytes (t = {L.RS_NSYM//2}), FCR = {L.RS_FCR}
//   shortened codeword length N set at run time (cfg_rs_n), K = N - NSYM
//
//   LOAD  : receive N bytes, compute syndromes on the fly
//   BM    : Berlekamp-Massey, one iteration per clock
//   OMEGA : error evaluator polynomial, one coefficient per clock
//   CHIEN : Chien search + Forney, one byte position per clock
//   APPLY : correct up to t bytes (only if decoding succeeded)
//   OUT   : emit K data bytes
// Must match model/ldacs_ref.py:rs_decode()
// ============================================================================
module rs_dec #(
    parameter NSYM = {L.RS_NSYM},
    parameter FCR  = {L.RS_FCR}
)(
    input  wire       clk,
    input  wire       rst,
    input  wire [7:0] cfg_rs_n,
    input  wire       s_valid,
    output wire       s_ready,
    input  wire [7:0] s_data,
    output wire       m_valid,
    input  wire       m_ready,
    output wire [7:0] m_data,
    // status: one pulse per codeword
    output reg        st_done,
    output reg        st_fail,
    output reg [3:0]  st_nerr
);
    localparam T = NSYM / 2;
    localparam S_LOAD=4'd0, S_CHECK=4'd1, S_BM=4'd2, S_OMEGA=4'd3, S_CINIT=4'd4,
               S_CHIEN=4'd5, S_DECIDE=4'd6, S_APPLY=4'd7, S_OUT=4'd8;

    // ---------------- GF(2^8) helpers ----------------
    function [7:0] gf_mul;
        input [7:0] a, b;
        integer k;
        reg [7:0] p, aa;
        begin
            p = 8'd0; aa = a;
            for (k = 0; k < 8; k = k + 1) begin
                if (b[k]) p = p ^ aa;
                aa = aa[7] ? ((aa << 1) ^ 8'h{prim_low:02x}) : (aa << 1);
            end
            gf_mul = p;
        end
    endfunction

    function [7:0] gf_exp;   // alpha^e, e in 0..254
        input [7:0] e;
        begin
            case (e)
{exp_cases}
            default: gf_exp = 8'h00;
            endcase
        end
    endfunction

    function [7:0] gf_inv;
        input [7:0] a;
        begin
            case (a)
{inv_cases}
            default: gf_inv = 8'h00;
            endcase
        end
    endfunction

    // ---------------- state ----------------
    reg [3:0]  state;
    reg [7:0]  n, wa, p, oi;
    reg [7:0]  cw [0:254];
    reg [8*NSYM-1:0]     S;        // syndromes
    reg [8*(NSYM+1)-1:0] Lam, B;   // locator / helper polynomial (index = degree)
    reg [8*NSYM-1:0]     Om;       // evaluator
    reg [8*(NSYM+1)-1:0] lam_t;    // Chien running terms
    reg [8*NSYM-1:0]     om_t;
    reg [7:0]  f_t, bb;
    reg [4:0]  L, m, r;
    reg [3:0]  nroots, ai;
    reg        fail;
    reg [8*T-1:0] epos, eval;

    assign s_ready = (state == S_LOAD);
    assign m_valid = (state == S_OUT);
    assign m_data  = cw[p];

    // ---------------- combinational datapath ----------------
    integer i, j;
    reg [8*NSYM-1:0]     S_next;
    reg [7:0]            disc, coef, omc, lsum, lodd, osum, ev;
    reg [8*(NSYM+1)-1:0] Lam_upd, lam_t_next;
    reg [8*NSYM-1:0]     om_t_next;
    always @* begin
        // syndrome update with incoming byte
        for (j = 0; j < NSYM; j = j + 1)
            S_next[j*8 +: 8] = gf_mul((wa == 0) ? 8'd0 : S[j*8 +: 8], gf_exp((FCR + j) % 255)) ^ s_data;
        // BM discrepancy + candidate update
        disc = S[r*8 +: 8];
        for (i = 1; i <= NSYM; i = i + 1)
            if (i <= L && i <= r)
                disc = disc ^ gf_mul(Lam[i*8 +: 8], S[(r-i)*8 +: 8]);
        coef = gf_mul(disc, gf_inv(bb));
        for (i = 0; i <= NSYM; i = i + 1)
            Lam_upd[i*8 +: 8] = Lam[i*8 +: 8] ^ ((i >= m) ? gf_mul(coef, B[(i-m)*8 +: 8]) : 8'd0);
        // Omega coefficient oi
        omc = 8'd0;
        for (j = 0; j < NSYM; j = j + 1)
            if (j <= oi)
                omc = omc ^ gf_mul(S[(oi-j)*8 +: 8], Lam[j*8 +: 8]);
        // Chien / Forney evaluation at alpha^-p
        lsum = 8'd0; lodd = 8'd0; osum = 8'd0;
        for (j = 0; j <= NSYM; j = j + 1) begin
            lsum = lsum ^ lam_t[j*8 +: 8];
            if (j % 2 == 1) lodd = lodd ^ lam_t[j*8 +: 8];
            lam_t_next[j*8 +: 8] = gf_mul(lam_t[j*8 +: 8], gf_exp((255 - (j % 255)) % 255));
        end
        for (j = 0; j < NSYM; j = j + 1) begin
            osum = osum ^ om_t[j*8 +: 8];
            om_t_next[j*8 +: 8] = gf_mul(om_t[j*8 +: 8], gf_exp((255 - (j % 255)) % 255));
        end
        ev = gf_mul(gf_mul(f_t, osum), gf_inv(lodd));
    end

    // ---------------- FSM ----------------
    always @(posedge clk) begin
        st_done <= 1'b0; st_fail <= 1'b0; st_nerr <= 4'd0;
        if (rst) begin
            state <= S_LOAD; wa <= 0; p <= 0;
        end else case (state)
            S_LOAD: if (s_valid) begin
                if (wa == 0) n <= cfg_rs_n;
                cw[wa] <= s_data;
                S <= S_next;
                if (wa != 0 && wa == n - 1'b1) begin
                    wa <= 0; state <= S_CHECK;
                end else
                    wa <= wa + 1'b1;
            end
            S_CHECK: begin
                fail <= 1'b0; nroots <= 0; ai <= 0;
                if (S == 0) begin
                    p <= 0; state <= S_OUT;
                end else begin
                    Lam <= 1; B <= 1; L <= 0; m <= 1; bb <= 8'd1; r <= 0;
                    state <= S_BM;
                end
            end
            S_BM: begin
                if (disc == 8'd0)
                    m <= m + 1'b1;
                else begin
                    Lam <= Lam_upd;
                    if (2*L <= r) begin
                        B <= Lam; L <= r + 1'b1 - L; bb <= disc; m <= 1;
                    end else
                        m <= m + 1'b1;
                end
                r <= r + 1'b1;
                if (r == NSYM - 1) begin oi <= 0; state <= S_OMEGA; end
            end
            S_OMEGA: begin
                if (L > T) begin
                    fail <= 1'b1; state <= S_DECIDE;
                end else begin
                    Om[oi*8 +: 8] <= omc;
                    oi <= oi + 1'b1;
                    if (oi == NSYM - 1) state <= S_CINIT;
                end
            end
            S_CINIT: begin
                lam_t <= Lam; om_t <= Om; f_t <= 8'd1; p <= 0;
                state <= S_CHIEN;
            end
            S_CHIEN: begin
                if (lsum == 8'd0) begin
                    if (lodd == 8'd0 || nroots >= T)
                        fail <= 1'b1;
                    else begin
                        epos[nroots*8 +: 8] <= n - 1'b1 - p;
                        eval[nroots*8 +: 8] <= ev;
                        nroots <= nroots + 1'b1;
                    end
                end
                lam_t <= lam_t_next;
                om_t  <= om_t_next;
                f_t   <= gf_mul(f_t, gf_exp((255 - (FCR % 255)) % 255));
                p     <= p + 1'b1;
                if (p == n - 1'b1) state <= S_DECIDE;
            end
            S_DECIDE: begin
                if (fail || nroots != L) begin
                    fail <= 1'b1; nroots <= 0;
                end
                ai <= 0;
                state <= S_APPLY;
            end
            S_APPLY: begin
                if (ai == nroots) begin
                    p <= 0; state <= S_OUT;
                end else begin
                    cw[epos[ai*8 +: 8]] <= cw[epos[ai*8 +: 8]] ^ eval[ai*8 +: 8];
                    ai <= ai + 1'b1;
                end
            end
            S_OUT: if (m_ready) begin
                if (p == n - NSYM - 1) begin
                    state   <= S_LOAD;
                    st_done <= 1'b1;
                    st_fail <= fail;
                    st_nerr <= nroots;
                end else
                    p <= p + 1'b1;
            end
            default: state <= S_LOAD;
        endcase
    end
endmodule
"""
out = os.path.join(HERE, "..", "rtl", "rs_dec.v")
open(out, "w").write(v)
print("wrote", os.path.normpath(out))
